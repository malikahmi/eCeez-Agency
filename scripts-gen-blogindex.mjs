// Generates a lightweight blog index (no `content`) so pages that only need
// titles/metadata don't import the full ~886KB blogData content blob.
import fs from 'fs';

const files = ['src/data/blogData.ts','src/data/seoBlogData.ts','src/data/aiBlogData.ts','src/data/designBlogData.ts']
  .filter(f => fs.existsSync(f));

// We can't safely eval TS; instead extract per-post shallow fields with a tolerant scan.
function extract(src) {
  const out = [];
  // find each top-level object start after an array; scan id/title/category/date/image/excerpt/readTime/featured
  const idRe = /\bid:\s*(['"`])((?:\\.|(?!\1).)*)\1/g;
  let m;
  while ((m = idRe.exec(src))) {
    const start = m.index;
    // window until next 'id:' or 2000 chars
    const next = src.indexOf(' id:', idRe.lastIndex);
    const win = src.slice(start, next === -1 ? start + 2500 : Math.min(next, start + 2500));
    const field = (name) => {
      const r = new RegExp(name + ":\\s*(['\"`])((?:\\\\.|(?!\\1).)*)\\1");
      const mm = win.match(r); return mm ? mm[2] : '';
    };
    const boolField = (name) => new RegExp(name + ':\\s*true').test(win);
    out.push({
      id: m[2],
      title: field('title'),
      category: field('category'),
      date: field('date'),
      readTime: field('readTime'),
      image: field('image'),
      excerpt: field('excerpt'),
      featured: boolField('featured'),
      pillar: field('pillar'),
    });
  }
  return out;
}

let all = [];
for (const f of files) all = all.concat(extract(fs.readFileSync(f,'utf8')));
// de-dupe by id
const seen = new Set(); all = all.filter(p => !seen.has(p.id) && seen.add(p.id));

const header = `// AUTO-GENERATED by scripts-gen-blogindex.mjs — do not edit by hand.
// Lightweight index (no post \`content\`) for components that only need metadata.
export interface BlogIndexEntry { id: string; title: string; category: string; date: string; readTime: string; image: string; excerpt: string; featured: boolean; pillar: string; }
export const blogIndex: BlogIndexEntry[] = ${JSON.stringify(all, null, 2)};
`;
fs.writeFileSync('src/data/blogIndex.ts', header);
console.log('blogIndex.ts written:', all.length, 'entries,', (header.length/1024).toFixed(0)+'KB');
